/**
 * Which of the three engagement modes a source usually yields.
 *
 * The picker sits directly above the channel list, and that list is already
 * read by colour: green means submit it yourself for nothing, orange means it
 * needs a budget, purple means a person decides. The sources were the one
 * place in that column still painted a single grey, so a run was chosen
 * without any hint of what kind of work it would produce.
 *
 * The mapping is editorial, not derived — a run stores no source on the
 * channels it finds — so each is the mode that source produces most often,
 * not the only one it can produce.
 */
export type SourceTone =
  | "free_listing"
  | "paid_placement"
  | "outreach"
  | "catalogue"
  | "local";

export const sourceTones: Record<string, SourceTone> = {
  // Publications and partner pages sell placement; a media kit is the norm.
  web: "paid_placement",
  // G2 and the rest take a free vendor profile.
  reviews: "free_listing",
  // A newsletter or a channel is one person you write to.
  creators: "outreach",
  // You post yourself, but a moderator decides whether the post survives.
  communities: "outreach",
  // These two also submit themselves for nothing, so by mode they would be
  // green as well — three identical tiles in one row. They carry a tone of
  // their own instead, blue and berry, which no channel in the list wears.
  directories: "catalogue",
  local: "local",
};

